import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { build } = require('esbuild');

const packageDirectory = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(packageDirectory, 'src/webAppClient.ts');
const generatedPath = resolve(packageDirectory, 'src/generated/webAppClient.generated.ts');
const coreWebAppRuntimePath = resolve(packageDirectory, '../core/src/webAppRuntime.ts');
const checkOnly = process.argv.slice(2).includes('--check');

const result = await build({
  alias: {
    '@valerypopoff/rivet2-core/web-app-runtime': coreWebAppRuntimePath,
  },
  absWorkingDir: packageDirectory,
  bundle: true,
  entryPoints: [sourcePath],
  format: 'iife',
  legalComments: 'none',
  minify: false,
  platform: 'browser',
  target: ['es2022'],
  write: false,
});

const output = `// Generated by packages/node/scripts/build-web-app-client.mjs. Do not edit directly.\nexport const RIVET_WEB_APP_CLIENT_JS = ${JSON.stringify(result.outputFiles[0].text)};\n`;

if (checkOnly) {
  const existing = await readFile(generatedPath, 'utf8');
  if (existing !== output) {
    throw new Error(
      'The generated hosted web-app client is stale. Run yarn workspace @valerypopoff/rivet2-node build:web-app-client.',
    );
  }
} else {
  await mkdir(dirname(generatedPath), { recursive: true });
  await writeFile(generatedPath, output);
}
